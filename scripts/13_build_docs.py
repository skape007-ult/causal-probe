"""Build report/report.md and README.md from their templates by inlining generated tables.

Templates contain markers of the form  <!-- TABLE:name -->  which are replaced by
report/tables/name.md (written by 12_tables.py from results/*.json). Prose is hand-written;
numbers in tables are never typed by hand.
"""
import re

from causal_probe.config import ROOT

TABLES = ROOT / "report" / "tables"


def build(src, dst):
    text = src.read_text()

    def repl(m):
        p = TABLES / f"{m.group(1)}.md"
        return p.read_text().strip() if p.exists() else f"*(table `{m.group(1)}` not generated yet)*"
    out = re.sub(r"<!-- TABLE:([\w.-]+) -->", repl, text)
    dst.write_text("<!-- GENERATED by scripts/13_build_docs.py from " + src.name + "; edit the template, not this file -->\n" + out)
    print("built", dst.relative_to(ROOT))


if __name__ == "__main__":
    build(ROOT / "report" / "report_template.md", ROOT / "report" / "report.md")
    if (ROOT / "report" / "README_template.md").exists():
        build(ROOT / "report" / "README_template.md", ROOT / "README.md")
