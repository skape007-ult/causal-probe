"""Build report/report.md, report/benchmark_text_baselines.md and README.md from their templates.

Two kinds of marker are replaced, so that no number in the write-up is typed by hand:
  <!-- TABLE:name -->            the table report/tables/name.md (written by 12_tables.py)
  {{file.json|a/b/c|fmt}}        one value from results/file.json at path a -> b -> c
                                 fmt: ci   "0.895 [0.863, 0.919]"    est  "0.895"
                                      num  "0.895"   num2 "0.90"   pct "86%"   int "1,162"
                                      signed / signedci   with an explicit sign
A missing file or path becomes a visible "(pending: ...)" note, never a silent blank.
"""
import json
import re

from causal_probe.config import RESULTS, ROOT

TABLES = ROOT / "report" / "tables"
_cache = {}


def value(m):
    fname, path, fmt = m.group(1), m.group(2), m.group(3)
    try:
        if fname not in _cache:
            _cache[fname] = json.loads((RESULTS / fname).read_text())
        v = _cache[fname]
        for k in path.split("/"):
            v = v[int(k)] if isinstance(v, list) else v[k]
    except Exception:
        return f"(pending: {fname} {path})"
    if fmt in ("ci", "signedci"):
        f = "{:+.3f}" if fmt == "signedci" else "{:.3f}"
        return f"{f.format(v['est'])} [{f.format(v['lo'])}, {f.format(v['hi'])}]"
    if fmt == "est":
        return f"{v['est']:.3f}"
    if isinstance(v, dict) and "est" in v:
        v = v["est"]
    return {"num": lambda x: f"{x:.3f}", "num2": lambda x: f"{x:.2f}", "pct": lambda x: f"{100 * x:.0f}%",
            "pct1": lambda x: f"{100 * x:.1f}%", "int": lambda x: f"{int(x):,}", "signed": lambda x: f"{x:+.3f}",
            "str": str}[fmt](v)


def build(src, dst):
    text = src.read_text()

    def repl(m):
        p = TABLES / f"{m.group(1)}.md"
        return p.read_text().strip() if p.exists() else f"*(table `{m.group(1)}` not generated yet)*"
    out = re.sub(r"<!-- TABLE:([\w.-]+) -->", repl, text)
    out = re.sub(r"\{\{([\w.\-]+)\|([^|}]+)\|(\w+)\}\}", value, out)
    dst.write_text("<!-- GENERATED by scripts/13_build_docs.py from " + str(src.relative_to(ROOT)) + "; edit the template, not this file -->\n" + out)
    n = out.count("(pending:")
    print("built", dst.relative_to(ROOT), f"({n} pending values)" if n else "")


def stale_tables():
    """Tables are inlined as files; warn if any result file is newer than the oldest table."""
    tabs = list(TABLES.glob("*.md")); ress = list(RESULTS.glob("*.json"))
    if tabs and ress:
        oldest = min(t.stat().st_mtime for t in tabs)
        newer = sorted(r.name for r in ress if r.stat().st_mtime > oldest + 1)
        if newer:
            print(f"WARNING: {len(newer)} result file(s) are newer than the oldest table (e.g. {newer[0]}); "
                  "run scripts/12_tables.py before building the documents.")


if __name__ == "__main__":
    stale_tables()
    for src, dst in (("report/report_template.md", "report/report.md"),
                     ("report/benchmark_text_baselines_template.md", "report/benchmark_text_baselines.md"),
                     ("report/README_template.md", "README.md")):
        if (ROOT / src).exists():
            build(ROOT / src, ROOT / dst)
    # study material: study/templates/<name>.md -> study/<name>.md (same markers)
    for src in sorted((ROOT / "study" / "templates").glob("*.md")) if (ROOT / "study" / "templates").exists() else []:
        build(src, ROOT / "study" / src.name)
